"""Bounded push controller and independent displacement checks.

NOT enabled in production. Coordinates here are explicitly ROS map x/y/yaw,
not Habitat x/y/z. An adapter must transform source-pinned affordances and
native observations, bind episode/object identities, and enforce existing BT
safeguards. The controller only commands existing motion interfaces; it has no
object-transform or simulator-callback access.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
import math
from typing import Protocol

XY = tuple[float, float]
Pose = tuple[float, float, float]


def distance(a: XY, b: XY) -> float:
    return math.hypot(a[0] - b[0], a[1] - b[1])


def finite(values) -> bool:
    return all(math.isfinite(x) for x in values)


@dataclass(frozen=True)
class Affordance:
    """Authored reusable skill asset, not a reference full-task action plan."""

    key: str
    initial: XY
    target: XY
    approach: Pose
    trajectory: tuple[Pose, ...]
    radius: float = 0.08

    def __post_init__(self):
        values = (*self.initial, *self.target, *self.approach, self.radius)
        if not self.key or not finite(values) or not 0 < self.radius <= 0.2:
            raise ValueError("invalid affordance")
        if distance(self.initial, self.target) <= 2 * self.radius:
            raise ValueError("rail too short to distinguish initial and target")
        if not self.trajectory or not all(finite(p) and len(p) == 3 for p in self.trajectory):
            raise ValueError("authored contact trajectory required")


@dataclass(frozen=True)
class Observation:
    episode: str
    native_id: int
    key: str
    sequence: int
    received_at: float
    object_xy: XY
    robot_xy: XY
    activation: str  # none / physics_contact / proximity_fallback
    episode_initial_xy: XY | None = None
    episode_robot_travel: float | None = None
    episode_motion_observed: bool = False


class Motion(Protocol):
    """Adapter must keep normal safety/obstacle checks and stop discipline."""

    def approach(self, pose: Pose) -> None: ...
    def waypoint(self, pose: Pose, *, max_speed: float) -> None: ...
    def stop(self) -> None: ...


class PushController:
    """One invocation; every terminal path stops, mobility completion is not SR.

    Only measured, episode-bound displacement can return completed_verified.
    Pose samples and native observations are inputs, not generated by this class.
    Call tick regularly even while waiting for navigation. Cancellation must also
    propagate through the outer BT wrapper; this local stop is defense in depth.
    """

    def __init__(self, affordance: Affordance, episode: str, native_id: int,
                 motion: Motion, *, timeout: float = 90, stale_after: float = 1,
                 no_progress: float = 8, max_speed: float = 0.15, approach_radius: float = 0.2,
                 resume_enabled: bool = False):
        if not episode or native_id < 0 or not finite((timeout, stale_after, no_progress, max_speed, approach_radius)):
            raise ValueError("identity and finite limits required")
        if min(timeout, stale_after, no_progress, max_speed) <= 0 or max_speed > 0.2 or not 0.15 <= approach_radius <= 0.3:
            raise ValueError("invalid motion limits")
        self.asset, self.episode, self.native_id, self.motion = affordance, episode, native_id, motion
        self.resume_enabled = resume_enabled
        self.resumed = False
        self.approach_radius = approach_radius
        self.rail_length = distance(affordance.initial, affordance.target)
        self.approach_cross_track_tolerance = min(approach_radius, affordance.radius)
        self.approach_heading_tolerance = min(0.15, math.atan2(affordance.radius, self.rail_length))
        self.timeout, self.stale_after = timeout, stale_after
        self.no_progress, self.max_speed = no_progress, max_speed
        self.started = self.progress_at = None
        self.previous = None
        self.phase = "new"
        self.result = None
        self.index = 0
        self.progress = 0.0
        self.evidence = []
        self.saw_activation = False
        self.robot_travel = 0.0

    def approach_position_ready(self, pose) -> bool:
        dx = (self.asset.target[0] - self.asset.initial[0]) / self.rail_length
        dy = (self.asset.target[1] - self.asset.initial[1]) / self.rail_length
        cross = -(pose[0] - self.asset.approach[0]) * dy + (pose[1] - self.asset.approach[1]) * dx
        return (distance(pose[:2], self.asset.approach[:2]) <= self.approach_radius
                and abs(cross) <= self.approach_cross_track_tolerance)

    def _finish(self, reason: str) -> str:
        self.motion.stop()
        self.result = reason
        self.phase = "terminal"
        return reason

    def cancel(self) -> str:
        return self._finish("cancelled")

    def tick(self, now: float, robot_pose: Pose, pose_age: float,
             observation: Observation | None, *, cancelled: bool = False,
             blocked: bool = False) -> str:
        if self.result is not None:
            return self.result
        try:
            return self._tick(now, robot_pose, pose_age, observation, cancelled, blocked)
        except Exception:
            self._finish("adapter_error")
            raise

    def _tick(self, now, pose, age, obs, cancelled, blocked):
        if cancelled:
            return self._finish("cancelled")
        if not finite((*pose, now, age)) or age < 0 or age > self.stale_after:
            return self._finish("stale_pose")
        if blocked:
            return self._finish("blocked")
        if obs is None:
            return self._finish("feedback_missing")
        if (obs.episode, obs.native_id, obs.key) != (self.episode, self.native_id, self.asset.key):
            return self._finish("feedback_identity_mismatch")
        if (not finite((*obs.object_xy, *obs.robot_xy, obs.received_at))
                or not 0 <= now - obs.received_at <= self.stale_after
                or obs.activation not in {"none", "physics_contact", "proximity_fallback"}):
            return self._finish("feedback_invalid")
        if self.started is None:
            if self.resume_enabled:
                initial, travel = obs.episode_initial_xy, obs.episode_robot_travel
                if (initial is None or travel is None or not finite((*initial, travel))
                        or travel < 0 or distance(initial, self.asset.initial) > 1e-5):
                    return self._finish("episode_initialization_not_verified")
                dx = (self.asset.target[0] - self.asset.initial[0]) / self.rail_length
                dy = (self.asset.target[1] - self.asset.initial[1]) / self.rail_length
                along = (obs.object_xy[0] - self.asset.initial[0]) * dx + (obs.object_xy[1] - self.asset.initial[1]) * dy
                projected = (self.asset.initial[0] + along * dx, self.asset.initial[1] + along * dy)
                if distance(projected, obs.object_xy) > 1e-4 or not -1e-4 <= along <= self.rail_length + 1e-4:
                    return self._finish("resume_pose_off_rail")
                if along > self.asset.radius and (not obs.episode_motion_observed or travel < along - 1e-4):
                    return self._finish("resume_motion_not_verified")
                self.robot_travel = travel
                self.saw_activation = obs.episode_motion_observed
                if distance(obs.object_xy, self.asset.target) <= self.asset.radius:
                    if self.saw_activation and travel >= .05 and along > .05:
                        return self._finish("completed_verified")
                    return self._finish("resume_motion_not_verified")
                if along > self.asset.radius:
                    approach = (self.asset.approach[0] + along * dx,
                                self.asset.approach[1] + along * dy, self.asset.approach[2])
                    end = self.asset.trajectory[-1]
                    count = max(1, math.ceil(distance(approach[:2], end[:2]) / .1))
                    trajectory = tuple((approach[0] + (end[0]-approach[0])*i/count,
                                        approach[1] + (end[1]-approach[1])*i/count, end[2])
                                       for i in range(1, count+1))
                    self.asset = replace(self.asset, approach=approach, trajectory=trajectory)
                    self.resumed = True
                    self.progress = along
            elif distance(obs.object_xy, self.asset.initial) > self.asset.radius:
                # Original default remains unchanged until the retry repair is reviewed.
                return self._finish("reset_not_verified")
            self.started = self.progress_at = now
            self.phase = "approach"
            self.motion.approach(self.asset.approach)
        if now - self.started >= self.timeout:
            return self._finish("timeout")
        if self.previous is not None and obs.sequence < self.previous.sequence:
            return self._finish("feedback_sequence_invalid")
        if self.previous is None or obs.sequence > self.previous.sequence:
            if self.previous is not None:
                robot_delta = distance(obs.robot_xy, self.previous.robot_xy)
                object_delta = distance(obs.object_xy, self.previous.object_xy)
                # Reject unsupported motion and pose jumps; native telemetry is
                # sampled every update, with retained sequence continuity.
                if obs.sequence != self.previous.sequence + 1:
                    return self._finish("feedback_sequence_gap")
                if object_delta > 0.10 or (object_delta > 0.002 and robot_delta < 0.0001):
                    return self._finish("unexplained_object_motion")
                self.robot_travel += robot_delta
            self.evidence.append(obs)
            self.previous = obs
            if obs.activation != "none":
                self.saw_activation = True
            displacement = distance(obs.object_xy, self.asset.initial)
            if displacement > self.progress + 0.01:
                self.progress, self.progress_at = displacement, now
            if (self.phase == "contact" and distance(obs.object_xy, self.asset.target) <= self.asset.radius
                    and self.saw_activation and self.robot_travel >= 0.05):
                return self._finish("completed_verified")
        if self.phase == "approach":
            yaw_error = math.atan2(math.sin(pose[2] - self.asset.approach[2]),
                                   math.cos(pose[2] - self.asset.approach[2]))
            if self.approach_position_ready(pose) and abs(yaw_error) <= self.approach_heading_tolerance:
                self.phase, self.progress_at = "contact", now
                self.motion.waypoint(self.asset.trajectory[0], max_speed=self.max_speed)
        else:
            if now - self.progress_at >= self.no_progress:
                return self._finish("blocked_no_progress")
            goal = self.asset.trajectory[self.index]
            # Approach acceptance is wider than a dense waypoint's0.08m circle.
            # Retire a waypoint once the robot reaches/passes its along-rail
            # plane, rather than steering back to a point passed sideways.
            # This is subgoal progression only: native object displacement and
            # the existing no-progress/stop checks still determine the result.
            dx = self.asset.target[0] - self.asset.initial[0]
            dy = self.asset.target[1] - self.asset.initial[1]
            length = math.hypot(dx, dy)
            along_error = ((pose[0] - goal[0]) * dx + (pose[1] - goal[1]) * dy) / length
            if distance(pose[:2], goal[:2]) <= 0.08 or along_error >= -0.08:
                if self.index + 1 == len(self.asset.trajectory):
                    return self._finish("trajectory_complete_without_displacement")
                self.index += 1
                self.motion.waypoint(self.asset.trajectory[self.index], max_speed=self.max_speed)
        return "running"
